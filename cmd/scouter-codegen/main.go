package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strings"
)

type NodeType struct {
	Type     string               `json:"type"`
	Named    bool                 `json:"named"`
	Fields   map[string]NodeField `json:"fields"`
	Subtypes []NodeSubtype        `json:"subtypes"`
}

type NodeField struct {
	Multiple bool          `json:"multiple"`
	Required bool          `json:"required"`
	Types    []NodeSubtype `json:"types"`
}

type NodeSubtype struct {
	Type  string `json:"type"`
	Named bool   `json:"named"`
}

func main() {
	langName := flag.String("lang", "", "Language name (e.g. Python, Rust)")
	inPath := flag.String("in", "", "Path to node-types.json")
	outPath := flag.String("out", "", "Path to output Go file")
	whitelistStr := flag.String("whitelist", "", "Comma-separated list of node types to generate")
	flag.Parse()

	if *langName == "" || *inPath == "" || *outPath == "" {
		fmt.Println("Usage: scouter-codegen -lang <name> -in <node-types.json> -out <out.go> -whitelist <type1,type2,...>")
		os.Exit(1)
	}

	whitelist := make(map[string]bool)
	if *whitelistStr != "" {
		for _, w := range strings.Split(*whitelistStr, ",") {
			whitelist[strings.TrimSpace(w)] = true
		}
	}

	data, err := os.ReadFile(*inPath)
	if err != nil {
		fmt.Printf("Failed to read %s: %v\n", *inPath, err)
		os.Exit(1)
	}

	var nodes []NodeType
	if err := json.Unmarshal(data, &nodes); err != nil {
		fmt.Printf("Failed to parse JSON: %v\n", err)
		os.Exit(1)
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by scouter-codegen; DO NOT EDIT.\n")
	buf.WriteString("package ast_types\n\n")
	buf.WriteString("import \"github.com/odvcencio/gotreesitter\"\n\n")

	for _, node := range nodes {
		if !node.Named {
			continue
		}
		if len(whitelist) > 0 && !whitelist[node.Type] {
			continue
		}

		structName := toCamelCase(*langName) + toCamelCase(node.Type)
		
		// If it has subtypes, we treat it as an interface
		if len(node.Subtypes) > 0 {
			buf.WriteString(fmt.Sprintf("const Type%s = \"%s\"\n", structName, node.Type))
			buf.WriteString(fmt.Sprintf("type %s interface {\n", structName))
			buf.WriteString(fmt.Sprintf("\tIs%s()\n", structName))
			buf.WriteString("}\n\n")
			continue
		}

		buf.WriteString(fmt.Sprintf("const Type%s = \"%s\"\n", structName, node.Type))
		buf.WriteString(fmt.Sprintf("type %s struct {\n", structName))
		buf.WriteString("\tNode *gotreesitter.Node\n")
		buf.WriteString("\tLang *gotreesitter.Language\n")
		buf.WriteString("}\n\n")

		// Constructor
		buf.WriteString(fmt.Sprintf("func New%s(node *gotreesitter.Node, lang *gotreesitter.Language) *%s {\n", structName, structName))
		buf.WriteString(fmt.Sprintf("\treturn &%s{Node: node, Lang: lang}\n", structName))
		buf.WriteString("}\n\n")

		// Fields
		for fieldName := range node.Fields {
			methodName := toCamelCase(fieldName)
			buf.WriteString(fmt.Sprintf("func (n *%s) %s() *gotreesitter.Node {\n", structName, methodName))
			buf.WriteString(fmt.Sprintf("\treturn n.Node.ChildByFieldName(\"%s\", n.Lang)\n", fieldName))
			buf.WriteString("}\n\n")
		}
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Printf("Failed to format generated code: %v\n", err)
		// write unformatted for debugging
		os.WriteFile(*outPath, buf.Bytes(), 0644)
		os.Exit(1)
	}

	if err := os.WriteFile(*outPath, formatted, 0644); err != nil {
		fmt.Printf("Failed to write %s: %v\n", *outPath, err)
		os.Exit(1)
	}
	fmt.Printf("Generated %s successfully.\n", *outPath)
}

func toCamelCase(s string) string {
	parts := strings.Split(s, "_")
	var result string
	for _, p := range parts {
		if p == "" {
			continue
		}
		result += strings.ToUpper(p[:1]) + p[1:]
	}
	return result
}
